import { readdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { format } from "prettier";
const root = fileURLToPath(new URL("../examples/", import.meta.url));
const entries = [];
for (const file of (await readdir(root)).sort()) {
  if (!file.endsWith(".tsx") || file === "renderer.tsx") continue;
  const source = await readFile(path.join(root, file), "utf8");
  const expected = file.slice(0, -4).replaceAll("-", "") + "example";
  const candidates = [...source.matchAll(/export function (\w+Example)\(/g)];
  const exports =
    candidates.length === 1
      ? candidates
      : candidates.filter((match) => match[1].toLowerCase() === expected);
  if (exports.length !== 1)
    throw new Error(
      `${file}: export a named Example component matching the filename`,
    );
  entries.push([file.slice(0, -4), exports[0][1]]);
}
const names = `// Generated by pnpm examples:build. Do not edit.\nexport const exampleNames = new Set(${JSON.stringify(entries.map(([name]) => name))});\n`;
const index = `"use client";\n// Generated by pnpm examples:build. Do not edit.\nimport { lazy } from "react";\nexport const examples = {${entries.map(([name, component]) => `${JSON.stringify(name)}: lazy(() => import("./${name}").then(m => ({ default: m.${component} })))`).join(",")}};\nexport type ExampleName = keyof typeof examples;\n`;
for (const [file, source] of [
  ["names.ts", names],
  ["index.ts", index],
]) {
  const output = await format(source, { parser: "typescript" });
  if (
    (await readFile(path.join(root, file), "utf8").catch(() => "")) !== output
  )
    await writeFile(path.join(root, file), output);
}
console.log(`${entries.length} examples registered`);

// 문서에서 추가한 사례를 같은 Storybook 컴포넌트 아래에 등록합니다.
const manifest = JSON.parse(
  await readFile(new URL("../examples/manifest.json", import.meta.url), "utf8"),
);
const { mkdir, rm } = await import("node:fs/promises");
const storiesRoot = fileURLToPath(
  new URL("../stories/generated/", import.meta.url),
);
await mkdir(storiesRoot, { recursive: true });
const generated = new Set();
for (const component of manifest) {
  const doc = await readFile(
    new URL(`../docs/content/components/${component.id}.mdx`, import.meta.url),
    "utf8",
  );
  const cases = [...doc.matchAll(/<ComponentExample\b[^>]*>/g)].flatMap(
    ([tag]) => {
      const name = tag.match(/\bname="([^"]+)"/)?.[1];
      if (!name || name === component.id) return [];
      const entry = entries.find(([id]) => id === name);
      if (!entry) throw new Error(`Unknown documented example: ${name}`);
      const title = tag.match(/\btitle="([^"]+)"/)?.[1] ?? name;
      return [{ name, component: entry[1], title }];
    },
  );
  if (!cases.length) continue;
  const file = `${component.id}.stories.tsx`;
  generated.add(file);
  const source = `// Generated by pnpm examples:build. Edit the example and MDX instead.\nimport type { Meta, StoryObj } from "@storybook/react-vite";\n${cases.map((item, i) => `import { ${item.component} as Example${i} } from "../../examples/${item.name}";`).join("\n")}\nexport default { title: ${JSON.stringify(component.group + "/" + component.name)}, parameters: { controls: { disable: true } } } satisfies Meta;\n${cases
    .map(
      (item, i) =>
        `export const Case${item.name
          .split("-")
          .map((word) => word[0].toUpperCase() + word.slice(1))
          .join(
            "",
          )}: StoryObj = { name: ${JSON.stringify("예제 · " + item.title)}, render: () => <Example${i} /> };`,
    )
    .join("\n")}\n`;
  const output = await format(source, { parser: "typescript" });
  if (
    (await readFile(path.join(storiesRoot, file), "utf8").catch(() => "")) !==
    output
  )
    await writeFile(path.join(storiesRoot, file), output);
}
for (const file of await readdir(storiesRoot)) {
  if (file.endsWith(".stories.tsx") && !generated.has(file))
    await rm(path.join(storiesRoot, file));
}
